package com.claude.agent.llm

import java.time.ZonedDateTime
import java.time.format.DateTimeFormatter

/**
 * Провайдер системных промптов для разных LLM моделей.
 * 
 * Каждая модель может иметь свой оптимизированный системный промпт:
 * - Claude: подробные инструкции, детальные описания
 * - Qwen: краткие, четкие инструкции, минимум текста
 */
interface SystemPromptProvider {
    /**
     * Возвращает базовый системный промпт для обычного режима
     */
    fun getDefaultModePrompt(): String
    
    /**
     * Возвращает системный промпт для режима сбора требований (spec mode)
     */
    fun getSpecModePrompt(): String
    
    /**
     * Возвращает инструкции для формата JSON
     */
    fun getJsonFormatInstructions(): String
    
    /**
     * Возвращает инструкции для формата XML
     */
    fun getXmlFormatInstructions(): String
    
    /**
     * Возвращает промпт для работы с RAG контекстом
     */
    fun getRagPrompt(): String

    /**
     * Возвращает инструкции для работы с RAG (алиас для getRagPrompt)
     */
    fun getRagInstructions(): String = getRagPrompt()

    /**
     * Возвращает общие правила использования инструментов
     */
    fun getToolUsageRules(): String
}

/**
 * Провайдер системных промптов для Claude.
 * Использует подробные описания и детальные инструкции.
 */
class ClaudeSystemPromptProvider : SystemPromptProvider {
    
    override fun getDefaultModePrompt(): String = 
        "Ты — универсальный помощник. Отвечай на вопрос пользователя в зависимости от заданных параметров."
    
    override fun getSpecModePrompt(): String = """Ты — универсальный агент по сбору требований и контекста для задач пользователя.

Твоя цель:
1) Понять, какой результат нужен пользователю.
2) Задать минимум нужных вопросов.
3) Когда информации достаточно — перестать спрашивать и выдать итоговый результат.

Работай по шагам:

1. Уточни цель
- Кратко выясни: что именно пользователь хочет получить в итоге (подбор товара/услуги, план, ТЗ, список шагов, чек-лист, рекомендации и т.п.).
- Для кого это делается и в какой ситуации будет использоваться.

2. Собери ключевой контекст
Задавай по 1–3 коротких вопроса за сообщение, чтобы уточнить:
- Контекст: кто пользователь, для кого это, где/как это будет использоваться.
- Ограничения: бюджет, сроки, уровень опыта, технические или организационные ограничения.
- Предпочтения: что важнее (цена, качество, скорость, простота, бренд и т.д.).

3. Проверь достаточность данных
- Если уже понятно, что делать — сразу выдавай результат.
- Если чего-то критически не хватает — задай ещё 1–2 вопроса.
